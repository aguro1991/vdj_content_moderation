"""Tests for the VirtualDJ censor list generator."""

import subprocess
import sys
from pathlib import Path

import pytest
import yaml

import main

REPO_ROOT = Path(__file__).parent.parent
LISTS_DIR = REPO_ROOT / "lists"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def generate_to_tmp(tmp_path, policy="precision"):
    """Run generate() into a temp directory and return the three output files."""
    main.generate(policy, tmp_path)
    files = {}
    for fname in ["no-slurs-no-sex.txt", "conventions.txt", "child-friendly.txt"]:
        files[fname] = (tmp_path / fname).read_text()
    return files


def parse_terms(text):
    """Parse a space-separated output file into a set of terms."""
    return set(text.split()) if text.strip() else set()


def load_all_forms(yaml_filename):
    """Load all forms from a YAML list file."""
    data = yaml.safe_load((LISTS_DIR / yaml_filename).read_text())
    forms = []
    for entry in data["words"]:
        forms.extend(entry["forms"])
    return forms


# ---------------------------------------------------------------------------
# YAML structure tests
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("yaml_file", [
    "slurs.yaml",
    "sexual-content.yaml",
    "severe-swear-words.yaml",
    "other-swear-words.yaml",
])
def test_yaml_valid_and_structured(yaml_file):
    """Every YAML file is valid and uses structured entries with term + forms."""
    data = yaml.safe_load((LISTS_DIR / yaml_file).read_text())
    assert "words" in data
    for entry in data["words"]:
        assert "term" in entry, f"Missing 'term' in {yaml_file}: {entry}"
        assert "forms" in entry, f"Missing 'forms' in {yaml_file}: {entry}"
        assert isinstance(entry["forms"], list)
        assert len(entry["forms"]) > 0


def test_no_bare_strings_in_yaml():
    """No YAML entry should be a bare string — all must be structured."""
    for yaml_file in LISTS_DIR.glob("*.yaml"):
        data = yaml.safe_load(yaml_file.read_text())
        for entry in data["words"]:
            assert isinstance(entry, dict), \
                f"Bare string '{entry}' found in {yaml_file.name}"


