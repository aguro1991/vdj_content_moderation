# Ambiguous policy: ho
# ---------------------------------------------------------------------------

def test_precision_omits_ho(tmp_path):
    """Precision policy omits 'ho' and its forms from all outputs."""
    files = generate_to_tmp(tmp_path, policy="precision")
    for fname, content in files.items():
        terms = parse_terms(content)
        for ho_form in ["ho", "hos", "ho's"]:
            assert ho_form not in terms, \
                f"'{ho_form}' should be omitted in precision mode but found in {fname}"


def test_recall_includes_ho(tmp_path):
    """Recall policy includes 'ho' and its forms in outputs."""
    files = generate_to_tmp(tmp_path, policy="recall")
    # ho is in sexual-content.yaml, so it should be in all three cumulative files
    for fname, content in files.items():
        terms = parse_terms(content)
        assert "ho" in terms, f"'ho' should be present in recall mode but missing from {fname}"


def test_precision_omits_only_ho(tmp_path):
    """Precision mode omits only 'ho' — no other term should be dropped."""
    files_recall = generate_to_tmp(tmp_path, policy="recall")
    files_precision = generate_to_tmp(tmp_path, policy="precision")

    recall_terms = set()
    precision_terms = set()
    for content in files_recall.values():
        recall_terms |= parse_terms(content)
    for content in files_precision.values():
        precision_terms |= parse_terms(content)

    removed = recall_terms - precision_terms
    # Only ho-family terms should be removed
    assert removed == {"ho", "hos", "ho's"}, \
        f"Precision removed unexpected terms: {removed}"


