def test_no_duplicates(tmp_path):
    """Each output file has no duplicate terms."""
    files = generate_to_tmp(tmp_path, policy="recall")
    for fname, content in files.items():
        terms = content.split()
        assert len(terms) == len(set(terms)), \
            f"Duplicates in {fname}: {len(terms)} total, {len(set(terms))} unique"


def test_deterministic(tmp_path):
    """Generating twice produces identical output."""
    main.generate("recall", tmp_path)
    first = {f: (tmp_path / f).read_text()
             for f in ["no-slurs-no-sex.txt", "conventions.txt", "child-friendly.txt"]}

    tmp2 = tmp_path / "second"
    main.generate("recall", tmp2)
    second = {f: (tmp2 / f).read_text()
              for f in ["no-slurs-no-sex.txt", "conventions.txt", "child-friendly.txt"]}

    for fname in first:
        assert first[fname] == second[fname], \
            f"Non-deterministic output for {fname}"


def test_sorted(tmp_path):
    """Terms in each output file are sorted."""
    files = generate_to_tmp(tmp_path, policy="recall")
    for fname, content in files.items():
        terms = content.split()
        assert terms == sorted(terms), f"{fname} is not sorted"


# ---------------------------------------------------------------------------
# Cumulative membership
# ---------------------------------------------------------------------------

def test_cumulative_membership(tmp_path):
    """Each file is a superset of the previous severity tier."""
    files = generate_to_tmp(tmp_path, policy="recall")
    nsns = parse_terms(files["no-slurs-no-sex.txt"])
    conv = parse_terms(files["conventions.txt"])
    child = parse_terms(files["child-friendly.txt"])

    assert nsns <= conv, "conventions.txt missing terms from no-slurs-no-sex.txt"
    assert conv <= child, "child-friendly.txt missing terms from conventions.txt"


def test_cumulative_growth(tmp_path):
    """Each file has more terms than the previous tier."""
    files = generate_to_tmp(tmp_path, policy="recall")
    nsns = len(parse_terms(files["no-slurs-no-sex.txt"]))
    conv = len(parse_terms(files["conventions.txt"]))
    child = len(parse_terms(files["child-friendly.txt"]))
    assert nsns < conv < child, \
        f"Expected increasing counts: {nsns} < {conv} < {child}"


