def test_output_not_empty(tmp_path):
    """All output files are non-empty."""
    files = generate_to_tmp(tmp_path)
    for fname, content in files.items():
        assert content.strip(), f"{fname} is empty"


def test_output_only_ascii(tmp_path):
    """Output contains only ASCII characters (VirtualDJ compatibility)."""
    files = generate_to_tmp(tmp_path, policy="recall")
    for fname, content in files.items():
        try:
            content.encode("ascii")
        except UnicodeEncodeError:
            pytest.fail(f"{fname} contains non-ASCII characters")


def test_no_regex_syntax_in_output(tmp_path):
    """Output contains only literal terms, no regex metacharacters."""
    files = generate_to_tmp(tmp_path, policy="recall")
    # Apostrophes and hyphens are OK (literal characters). Backslashes,
    # brackets, parens, pipes, carets, dollar signs are not.
    forbidden = {"\\", "[", "]", "(", ")", "|", "^", "$", "*", "+", "?"}
    for fname, content in files.items():
        for ch in forbidden:
            assert ch not in content, \
                f"Regex metacharacter '{ch}' found in {fname}"
